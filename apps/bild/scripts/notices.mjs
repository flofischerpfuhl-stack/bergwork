import { mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { inventory, licenseText, root, selectedLicenses } from './license-inventory.mjs';

const noticePath = resolve(root, 'THIRD_PARTY_NOTICES.md');
const licensesPath = resolve(root, 'LICENSES');
const licenseIndexPath = resolve(licensesPath, 'THIRD_PARTY.md');
const jsonPath = resolve(root, 'public/licenses.json');
const curatedMarker = '<!-- curated:start -->';

function cell(value) { return String(value).replaceAll('|', '\\|').replaceAll('\n', ' '); }

function table(packages) {
  return ['| Package | Version | Licence expression | Source |', '| --- | --- | --- | --- |',
    ...packages.map((pkg) => `| ${cell(pkg.name)} | ${cell(pkg.version)} | ${cell(pkg.license)} | ${cell(pkg.homepage)} |`),
  ].join('\n');
}

export function renderNotices(npm, rust, extra, curatedText) {
  return `# Third-party notices

This file is generated by \`npm run notices\` from the installed production npm graph, every package in the locked
Rust/Tauri graph (including target-specific crates), and the curated inventory of vendored, downloaded, and opt-in
components. Complete applicable licence texts are generated in \`LICENSES/\`; the same inventory is available to the
offline application in \`public/licenses.json\`.

## npm production dependency inventory (${npm.length} packages)

${table(npm)}

## Rust/Tauri locked dependency inventory (${rust.length} crates)

${table(rust)}

## Vendored, model, font, and opt-in component inventory (${extra.length} components)

${table(extra)}

${curatedMarker}

${curatedText.trim()}
`;
}

export function publicInventory(entries) {
  return {
    version: 1,
    generatedBy: 'scripts/notices.mjs',
    entries: entries.map(({ manifestPath: _manifestPath, ...entry }) => entry),
  };
}

export function renderLicenseIndex(textIds) {
  return `# Third-party licence texts

This index is generated by \`npm run notices\`. The complete component inventory and attribution details are in
[THIRD_PARTY_NOTICES.md](../THIRD_PARTY_NOTICES.md).

${[...textIds].sort().map((textId) => `- [${textId}](${textId}.txt)`).join('\n')}
`;
}

function licensesFor(entry) {
  const selected = selectedLicenses(entry.license, entry.category);
  if (!selected) throw new Error(`Unknown or disallowed licence: ${entry.name}@${entry.version} (${entry.license})`);
  return selected;
}

export function generateNotices() {
  const existing = readFileSync(noticePath, 'utf8');
  const markerAt = existing.indexOf(curatedMarker);
  const curatedText = markerAt >= 0 ? existing.slice(markerAt + curatedMarker.length).trim()
    : existing.replace(/^# Third-party notices\s*/i, '').trim();
  const { npm, rust, entries } = inventory();
  const extra = entries.filter((entry) => !entry.id.startsWith('npm:') && !entry.id.startsWith('cargo:'));

  mkdirSync(licensesPath, { recursive: true });
  for (const name of readdirSync(licensesPath)) {
    if (name.endsWith('.txt')) unlinkSync(resolve(licensesPath, name));
  }
  const combinations = new Map();
  for (const entry of entries) combinations.set(entry.textId, licensesFor(entry));
  for (const [textId, ids] of combinations) {
    const complete = ids.map((id) => `===== ${id} =====\n\n${licenseText(id, rust).trim()}`).join('\n\n');
    writeFileSync(resolve(licensesPath, `${textId}.txt`), complete + '\n');
  }

  writeFileSync(licenseIndexPath, renderLicenseIndex(combinations.keys()));
  writeFileSync(noticePath, renderNotices(npm, rust, extra, curatedText));
  writeFileSync(jsonPath, JSON.stringify(publicInventory(entries), null, 2) + '\n');
  return { npm: npm.length, rust: rust.length, extra: extra.length, texts: combinations.size };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = generateNotices();
  console.log(`Wrote THIRD_PARTY_NOTICES.md, public/licenses.json, and ${result.texts} full licence text files (${result.npm} npm packages, ${result.rust} Rust crates, ${result.extra} curated components).`);
}
