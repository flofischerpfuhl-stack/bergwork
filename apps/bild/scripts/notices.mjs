import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const noticePath = resolve(root, 'THIRD_PARTY_NOTICES.md');
const curatedMarker = '<!-- curated:start -->';

function run(command, args) {
  return execFileSync(command, args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

function text(value, fallback = 'Not declared') {
  if (typeof value === 'string' && value.trim()) return value.trim();
  if (value && typeof value === 'object' && typeof value.url === 'string') return value.url;
  return fallback;
}

function cell(value) { return String(value).replaceAll('|', '\\|').replaceAll('\n', ' '); }

function npmPackages() {
  const rootPackage = JSON.parse(run('npm', ['ls', '--omit=dev', '--all', '--json', '--long']));
  const packages = new Map();
  const visit = (dependencies = {}) => {
    for (const [name, dependency] of Object.entries(dependencies)) {
      if (!dependency || typeof dependency !== 'object') continue;
      if (typeof dependency.version !== 'string') continue; // unmet optional peer placeholder, not installed code
      const version = dependency.version;
      const key = `${name}@${version}`;
      if (!packages.has(key)) {
        let manifest = {};
        try { manifest = JSON.parse(readFileSync(resolve(dependency.path, 'package.json'), 'utf8')); } catch { /* npm data is authoritative when no path exists */ }
        const repository = text(dependency.repository ?? manifest.repository,
          text(dependency.homepage ?? manifest.homepage, '—'));
        packages.set(key, { name, version, license: text(dependency.license ?? manifest.license), repository });
      }
      visit(dependency.dependencies);
    }
  };
  visit(rootPackage.dependencies);
  return [...packages.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function rustPackages() {
  const manifest = resolve(root, 'src-tauri/Cargo.toml');
  const metadata = JSON.parse(run('cargo', ['metadata', '--manifest-path', manifest, '--locked', '--format-version', '1']));
  const tree = run('cargo', ['tree', '--manifest-path', manifest, '--locked', '--edges', 'normal,build',
    '--prefix', 'none', '--no-dedupe']);
  const active = new Set();
  for (const line of tree.split('\n')) {
    const match = /^([A-Za-z0-9_.+-]+) v([^ ]+)/.exec(line);
    if (match && match[1] !== 'fernwork-bildeditor') active.add(`${match[1]}@${match[2]}`);
  }
  return metadata.packages
    .filter((pkg) => active.has(`${pkg.name}@${pkg.version}`))
    .map((pkg) => ({ name: pkg.name, version: pkg.version,
      license: text(pkg.license, pkg.license_file ? `See ${pkg.license_file}` : 'Not declared'),
      repository: text(pkg.repository, text(pkg.homepage, 'https://crates.io/crates/' + pkg.name)) }))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function table(packages) {
  return ['| Package | Version | Licence expression | Source |', '| --- | --- | --- | --- |',
    ...packages.map((pkg) => `| ${cell(pkg.name)} | ${cell(pkg.version)} | ${cell(pkg.license)} | ${cell(pkg.repository)} |`),
  ].join('\n');
}

const existing = readFileSync(noticePath, 'utf8');
const markerAt = existing.indexOf(curatedMarker);
const curated = markerAt >= 0 ? existing.slice(markerAt + curatedMarker.length).trim()
  : existing.replace(/^# Third-party notices\s*/i, '').trim();
const npm = npmPackages();
const rust = rustPackages();
const unknown = [...npm, ...rust].filter((pkg) => pkg.license === 'Not declared');
if (unknown.length) throw new Error(`Dependencies without declared licences: ${unknown.map((pkg) => pkg.name).join(', ')}`);

const generated = `# Third-party notices

This file is generated by \`npm run notices\` from the installed production npm graph and the locked Rust
normal/build dependency graph for the current release target. The tables reproduce package metadata; complete
licence texts accompany the installed packages and source distributions. The curated sections record bundled,
downloaded, native, and development-only material that package managers cannot discover.

## npm production dependency inventory (${npm.length} packages)

${table(npm)}

## Rust release dependency inventory (${rust.length} crates)

${table(rust)}

${curatedMarker}

${curated}
`;

writeFileSync(noticePath, generated);
console.log(`Wrote THIRD_PARTY_NOTICES.md (${npm.length} npm packages, ${rust.length} Rust crates).`);
