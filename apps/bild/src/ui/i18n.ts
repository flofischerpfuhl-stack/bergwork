const isApple = typeof navigator !== 'undefined' && /Mac|iPhone|iPad/.test(navigator.platform || navigator.userAgent);

/** Modifier names as the keyboard labels them: ⌘/Option on Apple devices, Ctrl/Alt (Strg/Alt) elsewhere. */
export function platformKeys(text: string, locale: Locale, apple = isApple): string {
  if (apple) return text;
  const ctrl = locale === 'de' ? 'Strg' : 'Ctrl';
  // "⌘-drag" → "Ctrl-drag", "⌘D" → "Ctrl+D", a lone "⌘" → "Ctrl".
  return text.replace(/⌘(-)?(\S)?/g, (_m, dash: string | undefined, next: string | undefined) =>
    dash ? `${ctrl}-${next ?? ''}` : next ? `${ctrl}+${next}` : ctrl).replace(/\bOption\b/g, 'Alt');
}

/** Undo names made from an adjustment kind ("New Curves Adjustment") read naturally in German too. */
function dynamicGerman(text: string): string | null {
  const created = /^New (.+) Adjustment$/.exec(text);
  if (created) return `Neue Einstellungsebene ${de[created[1]!] ?? created[1]}`;
  const edited = /^Edit (.+) Adjustment$/.exec(text);
  if (edited) return `Einstellungsebene ${de[edited[1]!] ?? edited[1]} bearbeiten`;
  return null;
}

export function translator(locale: Locale): (text: string) => string {
  if (locale === 'en') return (text) => platformKeys(ADJUST_P2_EN[text] ?? text, locale);
  return (text) => platformKeys(de[text] ?? dynamicGerman(text) ?? text, locale);
}
